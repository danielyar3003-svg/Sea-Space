PLACEHOLDER = __import__("re").compile(r"\{(\w+)(?=[},])")


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "lib" / "l10n"
    out.mkdir(parents=True, exist_ok=True)
    for idx, lang in enumerate(("en", "ru", "uk")):
        arb: dict[str, object] = {"@@locale": lang}
        for key, values in S.items():
            text = values[idx]
            arb[key] = text
            if lang == "en":
                names = []
                for m in PLACEHOLDER.finditer(text):
                    if m.group(1) not in names and m.group(1) not in ("one", "few", "many", "other"):
                        names.append(m.group(1))
                if names:
                    arb[f"@{key}"] = {"placeholders": {
                        n: {"type": "int"} if n in ("count", "phase") else {"type": "String"} for n in names
                    }}
        (out / f"app_{lang}.arb").write_text(json.dumps(arb, ensure_ascii=False, indent=2) + "\n")
    print(f"{len(S)} strings × 3 languages written to {out}")


if __name__ == "__main__":
    main()
